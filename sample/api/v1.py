@router.get("/search/blast", response_model=List[schemas.BlastHit], tags=["search"],
            responses={503: {"model": schemas.ErrorResponse}},
            summary="BLAST a sequence against the peptide database")
def blast_search(
    sequence: str = Query(..., description="Query sequence, plain or FASTA."),
    max_hits: int = Query(50, ge=1, le=500),
) -> Any:
    """
    Runs blastp against the released peptides.

    Synchronous: against 35,411 short peptides a blastp query returns in well under a second, so
    queueing it would add a poll cycle for no benefit. HMMER and embedding search (below) turned
    out to be just as fast once built and are synchronous for the same reason; the queued pattern
    is reserved for something genuinely slow, like a prospective RefSeq screen would be.

    :returns: Alignments, best first.
    :raises HTTPException: 503 when the BLAST database is not built.
    """
    db_path = init_blast_database()
    if not db_path:
        raise HTTPException(status_code=503,
                            detail="BLAST database unavailable; the consensus dataset is missing.")
    return run_blast_search(sequence, db_path, max_hits=max_hits)


@router.get("/search/hmmer", response_model=List[schemas.FamilyHmmHit], tags=["search"],
            responses={503: {"model": schemas.ErrorResponse}},
            summary="Scan a sequence against SAMPLE's derived family HMM profiles")
def hmmer_search(
    sequence: str = Query(..., description="Query sequence, plain or FASTA."),
    max_hits: int = Query(50, ge=1, le=500),
) -> Any:
    """
    Runs `hmmscan` against the 519 profile HMMs built from SAMPLE's own near-identity clusters
    (`sample.family_hmms`) -- not Pfam, which is assigned the other direction at ingestion time
    and already exposed through `GET /families`.

    Synchronous, like `/search/blast`: 519 small profiles score in well under a second, so
    queueing would add a poll cycle for no benefit.

    :returns: Family hits, best (lowest) E-value first. Never includes `SAMPLE_FAM_000001`, whose
        profile does not reliably score even its own members -- see `KNOWN_ISSUES.md`.
    :raises HTTPException: 503 when the family HMM database has not been built.
    """
    db_path = family_hmm_database_path()
    if not db_path:
        raise HTTPException(status_code=503,
                            detail="Family HMM database unavailable; run "
                                   "`sample-cli build-family-hmms --press`.")
    return run_hmm_search(sequence, db_path, max_hits=max_hits)


@router.get("/search/embedding", response_model=List[schemas.EmbeddingHit], tags=["search"],
            responses={503: {"model": schemas.ErrorResponse}},
            summary="Find peptides nearest to a sequence in ESM-2 embedding space")
def embedding_search(
    sequence: str = Query(..., description="Query sequence, plain or FASTA."),
    max_hits: int = Query(50, ge=1, le=500),
) -> Any:
    """
    Embeds the query with ESM-2 (`facebook/esm2_t6_8M_UR50D`) and finds the released peptides
    closest to it by cosine similarity, via a Chroma index built over the whole real corpus
    (`sample.embeddings`).

    Complements BLAST and HMMER rather than replacing either: a representation-space neighbor can
    be functionally similar with too little raw sequence identity for either of those to find it.

    Synchronous, like `/search/blast` and `/search/hmmer`: embedding one query sequence is a
    single forward pass through an 8M-parameter model, measured at single-digit milliseconds once
    the model is loaded (cached in-process after the first request), and the k-NN query itself is
    well under that against the 37,042 indexed vectors.

    :returns: Hits ordered by descending similarity.
    :raises HTTPException: 503 when the embedding index has not been built.
    """
    index_path = embedding_index_path()
    if not index_path:
        raise HTTPException(status_code=503,
                            detail="Embedding index unavailable; run "
                                   "`sample-cli build-embedding-index`.")
    return run_embedding_search(sequence, index_path, max_hits=max_hits)
