"""
The versioned JSON API.

Separate from the HTML pages so the two can evolve independently: the pages are free to change
shape with the templates, while anything under ``/api/v1`` is a contract. FastAPI derives the
OpenAPI document from the response models declared here, which is why no separate spec file is
maintained -- a hand-written spec drifts from the code it describes.

Both share :mod:`sample.db`, so the decoy exclusion is enforced once for both.
"""
import logging
import uuid
from typing import Any, List

from fastapi import APIRouter, HTTPException, Query, Request
from fastapi.responses import Response

from sample import db
from sample.api import schemas
from sample.api.common import (embedding_index_path, family_hmm_database_path,
                              init_blast_database, run_blast_search, run_embedding_search,
                              run_hmm_search)

logger = logging.getLogger("sample.api.v1")

router = APIRouter(prefix="/api/v1")

#: Upper bound on rows per request. Without it a client can ask for all 35,411 peptides with their
#: activities joined, which is a multi-second query and a large response.
MAX_PAGE_SIZE: int = 500


@router.get("/stats", response_model=schemas.Stats, tags=["dataset"],
            summary="Dataset counts")
def get_stats() -> Any:
    """
    :returns: Row counts for the released dataset.
    """
    return db.get_stats()


@router.get("/peptides", response_model=schemas.Page[schemas.PeptideSummary],
            tags=["peptides"], summary="List and filter peptides")
def list_peptides(
    q: str = Query("", description="Free text matched against id, sequence, SMILES and paper ids."),
    activity_group: str = Query("", description="Activity class, e.g. antibacterial."),
    target: str = Query("", description="Target organism substring."),
    mechanism: str = Query("", description="Mechanism of action substring."),
    metric: str = Query("", description="Assay type, e.g. MIC."),
    unit: str = Query("", description="Canonical unit, e.g. uM."),
    limit: int = Query(50, ge=1, le=MAX_PAGE_SIZE),
    offset: int = Query(0, ge=0),
) -> Any:
    """
    Paginated peptide collection.

    Decoys are excluded. They are training negatives generated by shuffling real sequences, and
    serving one here would present a fabricated sequence as a measured peptide.

    :returns: A page of peptide summaries.
    """
    rows, total = db.search_peptides(
        query_str=q, activity_group=activity_group, target=target, mechanism=mechanism,
        metric=metric, unit=unit, limit=limit, offset=offset)
    return {"items": rows, "total": total, "limit": limit, "offset": offset}


@router.get("/peptides/search", response_model=schemas.Page[schemas.PeptideSummary],
            tags=["peptides"], summary="Full-text or motif search",
            responses={400: {"model": schemas.ErrorResponse}})
def search_peptides_fulltext(
    q: str = Query(..., description="FTS5 expression: supports AND/OR/NOT, \"phrases\" and "
                                    "prefix wildcards such as magain*. In regex mode, a Python "
                                    "regular expression such as ^GIG.{2}[FL]."),
    mode: str = Query("fulltext", pattern="^(fulltext|regex)$",
                      description="fulltext for the FTS5 index, regex for a motif scan."),
    field: str = Query("sequence", description="Regex mode only: column to match against."),
    limit: int = Query(50, ge=1, le=MAX_PAGE_SIZE),
    offset: int = Query(0, ge=0),
) -> Any:
    """
    Search peptides by full text or by sequence motif.

    Two modes, because they answer different questions and FTS5 cannot serve the second. Full text
    is tokenised, so it finds whole terms and prefixes; it cannot express ``^GIG.{2}[FL]``, which
    is precisely the query a peptide database exists to answer.

    Their error behaviour differs deliberately. A malformed FTS5 expression returns an empty page,
    because it is usually accidental -- a bare parenthesis in a peptide name is FTS syntax. A
    malformed regex returns 400 with the error, because it was written deliberately and the
    message says what to fix.

    :returns: A page of matching peptides.
    :raises HTTPException: 400 for an invalid pattern, 504 when a motif scan exceeds its budget.
    """
    if mode == "regex":
        try:
            rows, total = db.regex_search(q, field=field, limit=limit, offset=offset)
        except db.InvalidPattern as e:
            raise HTTPException(status_code=400, detail=str(e)) from e
        except db.SearchTimeout as e:
            raise HTTPException(status_code=504, detail=str(e)) from e
    else:
        rows, total = db.full_text_search(q, limit=limit, offset=offset)
    return {"items": rows, "total": total, "limit": limit, "offset": offset}


@router.get("/search/similar", response_model=List[schemas.SimilarityHit], tags=["search"],
            summary="Near-identity peptide search")
def similarity_search(
    sequence: str = Query(..., description="Query peptide, one-letter code."),
    max_mismatches: int = Query(2, ge=0, le=5,
                                description="Substitutions tolerated."),
    max_hits: int = Query(50, ge=1, le=MAX_PAGE_SIZE),
) -> Any:
    """
    Finds released peptides within a few substitutions of the query.

    Complements ``/search/blast`` rather than replacing it. Half of this dataset is under 20
    residues, where BLAST's statistics stop being meaningful and its seeding misses genuine
    single-substitution analogues; this reports an exact mismatch count instead, which needs no
    statistical caveat. BLAST remains the better tool for longer or remotely similar sequences.

    :returns: Hits ordered by increasing mismatch count.
    """
    from sample import similarity

    return similarity.search(sequence, max_mismatches=max_mismatches, limit=max_hits)


@router.get("/families", response_model=schemas.Page[schemas.Family], tags=["families"],
            summary="List peptide families")
def list_families(
    source: str = Query("", pattern="^(pfam|cluster|)$",
                        description="Restrict to curated Pfam families or derived clusters."),
    limit: int = Query(50, ge=1, le=MAX_PAGE_SIZE),
    offset: int = Query(0, ge=0),
) -> Any:
    """
    Families, largest first.

    Two provenance levels share this list and are told apart by ``source``: ``pfam`` is a curated
    assignment made at Pfam's own gathering threshold, ``cluster`` is a group derived here by
    near-identity. Filter on it rather than treating the two as equivalent evidence.

    :returns: A page of families.
    """
    rows, total = db.list_families(source=source, limit=limit, offset=offset)
    return {"items": rows, "total": total, "limit": limit, "offset": offset}


