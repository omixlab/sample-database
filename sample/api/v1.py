@router.post("/annotate", response_model=schemas.AnnotationJobAccepted, status_code=202,
             tags=["annotate"],
             responses={400: {"model": schemas.ErrorResponse},
                        503: {"model": schemas.ErrorResponse}},
             summary="Queue a peptide annotation")
async def submit_annotation(payload: schemas.AnnotationRequest) -> Any:
    """
    Runs the annotator battery (HemoPI2, a Pfam scan, near-identical SAMPLE peptides) over one
    sequence and returns immediately.

    Asynchronous because the battery itself is slow, not because of batch size -- measured at
    ~20s for a single sequence (a Pfam scan against the full ~20,000-family Pfam-A database
    dominates that). See `sample.annotator`'s module docstring for the measurements and for which
    of the originally-planned tools are actually running yet.

    A sequence annotated successfully within the last week is returned immediately without
    queuing a new job -- `cached: true` in the response, and `result_url` already resolves.

    :param payload: The sequence to annotate.
    :returns: 202 with the job id and polling URLs, or an already-finished job when cached.
    """
    from sample import annotation_store
    from sample.tasks import annotate_peptide, broker_available

    sequence = (payload.sequence or "").strip()
    if not sequence:
        raise HTTPException(status_code=400, detail="No sequence supplied.")

    annotation_store.init_db()
    cached = annotation_store.find_cached_result(sequence)
    if cached is not None:
        return {"job_id": cached["job_id"], "status": annotation_store.STATUS_SUCCESS,
                "cached": True, "status_url": f"/api/v1/annotate/{cached['job_id']}",
                "result_url": f"/api/v1/annotate/{cached['job_id']}/result"}

    if not broker_available():
        raise HTTPException(
            status_code=503, detail="The annotation queue is unavailable; no job was created.")

    job_id = str(uuid.uuid4())
    annotation_store.create_job(job_id, sequence)

    try:
        async_result = annotate_peptide.delay(job_id, sequence)
        annotation_store.attach_task_id(job_id, async_result.id)
    except Exception as e:
        annotation_store.mark_finished(job_id, annotation_store.STATUS_FAILURE,
                                       error=f"Could not queue the job: {e}")
        raise HTTPException(status_code=503, detail=f"Could not queue the job: {e}")

    return {"job_id": job_id, "status": annotation_store.STATUS_PENDING, "cached": False,
            "status_url": f"/api/v1/annotate/{job_id}",
            "result_url": f"/api/v1/annotate/{job_id}/result"}


